import fs from 'node:fs';
import vm from 'node:vm';
const source = fs.readFileSync(new URL('../public/device/device-stack.js', import.meta.url), 'utf8');
const ctx = { console, Uint8Array, Uint32Array, ArrayBuffer, DataView, TextEncoder, TextDecoder, performance, setTimeout, clearTimeout };
ctx.window = ctx; vm.createContext(ctx); vm.runInContext(source, ctx);
const { MockTransport, DeviceClient, LogicAnalyzerService, JtagService } = ctx.WFL2;
const client = new DeviceClient(new MockTransport());
await client.connect();
const info = await client.getDeviceInfo();
if (!info.productName) throw new Error('device info missing');
const logic = new LogicAnalyzerService(client);
const cap = await logic.capture({ sampleRate: 24e6, sampleCount: 8192, enabledMask: 0xff });
if (cap.sampleCount !== 8192 || cap.channels.length !== 8) throw new Error('logic capture failed');
const jtag = new JtagService(client);
const chain = await jtag.scan();
if (chain.length < 1) throw new Error('jtag scan failed');
const bytes = new Uint8Array(13000); for (let i=0;i<bytes.length;i++) bytes[i]=i&255;
const fakeFile = { name:'demo.bit', size:bytes.length, arrayBuffer:async()=>bytes.buffer };
const result = await jtag.programFile(fakeFile, { onProgress:()=>{} });
if (!result.programmed || !result.verified) throw new Error('program mock failed');
await client.disconnect();
console.log(JSON.stringify({ ok:true, product:info.productName, logicSamples:cap.sampleCount, jtagDevices:chain.length, programmedBytes:result.bytes }, null, 2));
